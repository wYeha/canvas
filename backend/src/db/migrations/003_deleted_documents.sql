-- Миграция 003: журнал удалённых документов. Клиент удаляет свою копию, только если документ есть в журнале:
-- документ, просто отсутствующий на сервере (новая или восстановленная база), клиенты отправят заново.
CREATE TABLE deleted_documents (
  id TEXT PRIMARY KEY NOT NULL,
  deleted_at TEXT NOT NULL
) STRICT;
